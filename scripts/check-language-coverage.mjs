import fs from 'node:fs';
import path from 'node:path';

import { ensureDir, formatLanguages, markdownFiles, requiredExampleLanguages } from './review-utils.mjs';

const outputFile = path.join('docs', 'language-coverage-report.md');
const labels = new Map([
  ['c', 'C'],
  ['cpp', 'C++'],
  ['csharp', 'C#'],
  ['go', 'Go'],
  ['java', 'Java'],
  ['js', 'JavaScript'],
  ['python', 'Python'],
  ['rust', 'Rust'],
  ['ts', 'TypeScript'],
]);

const rows = [
  ...coverageRows('problems'),
  ...coverageRows('patterns'),
  ...coverageRows('concepts'),
];
const incomplete = rows.filter((row) => row.missing.length > 0);

ensureDir('docs');
fs.writeFileSync(outputFile, report(rows, incomplete));

console.log(
  `Language coverage: ${rows.length - incomplete.length}/${rows.length} content entries complete.`,
);
console.log(`Wrote ${outputFile}.`);

function coverageRows(type) {
  return markdownFiles(`src/content/${type}`).map((file) => {
    const source = fs.readFileSync(file, 'utf8');
    const present = exampleLanguages(source).filter((language) =>
      requiredExampleLanguages.includes(language),
    );
    const missing = requiredExampleLanguages.filter((language) => !present.includes(language));
    return {
      file,
      id: path.basename(file, '.md'),
      missing,
      present,
      type,
    };
  });
}

function exampleLanguages(source) {
  return [
    ...new Set(
      [...source.matchAll(/^```([A-Za-z0-9_+#-]+)/gm)]
        .map((match) => normalizeLanguage(match[1]))
        .filter(Boolean),
    ),
  ].sort(
    (left, right) =>
      requiredExampleLanguages.indexOf(left) - requiredExampleLanguages.indexOf(right),
  );
}

function normalizeLanguage(language) {
  const normalized = language.toLowerCase();
  if (normalized === 'c++') {
    return 'cpp';
  }
  if (normalized === 'cs') {
    return 'csharp';
  }
  if (normalized === 'javascript') {
    return 'js';
  }
  if (normalized === 'typescript' || normalized === 'tsx') {
    return 'ts';
  }
  if (normalized === 'py') {
    return 'python';
  }
  if (normalized === 'rs') {
    return 'rust';
  }
  return normalized;
}

function report(allRows, incompleteRows) {
  const byType = new Map();
  for (const row of allRows) {
    const bucket = byType.get(row.type) ?? { complete: 0, total: 0 };
    bucket.total += 1;
    if (row.missing.length === 0) {
      bucket.complete += 1;
    }
    byType.set(row.type, bucket);
  }

  return `# Language Coverage Report

Generated by \`node scripts/check-language-coverage.mjs\`.

Required launch languages: ${formatLanguages(requiredExampleLanguages)}

## Summary

${[...byType.entries()]
  .map(([type, counts]) => `- ${type}: ${counts.complete}/${counts.total} complete`)
  .join('\n')}

Overall: ${allRows.length - incompleteRows.length}/${allRows.length} complete.

## Interpretation

This report tracks real fenced code examples, not only metadata. Do not satisfy a missing language
by adding a token snippet or a mechanical translation that does not teach the problem. Missing
examples should become manual review work unless the language shape is clearly equivalent and easy
to verify.

## Incomplete Entries

${incompleteRows.map(entryLine).join('\n')}
`;
}

function entryLine(row) {
  const missing = row.missing.map((language) => labels.get(language) ?? language).join(', ');
  const present = row.present.map((language) => labels.get(language) ?? language).join(', ') || 'none';
  return `- \`${row.type}/${row.id}\`
  - Present: ${present}
  - Missing: ${missing}`;
}
